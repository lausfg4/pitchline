/**
 * Determina si el torneo sigue en la Fase de Liga (sin llaves eliminatorias de Octavos definidas aún).
 */
export function isStillInLeagueStage(
  standings: StandingRow[],
  matches: MatchWithDetails[]
): boolean {
  void standings;
  const knockoutStages = new Set([
    "ROUND_16",
    "LAST_16",
    "R16",
    "QUARTER_FINALS",
    "QF",
    "SEMI_FINALS",
    "SF",
    "FINAL",
    "KNOCKOUT",
  ]);

  const hasDefinedKnockoutMatches = matches.some(
    (m) =>
      Boolean(m.bracket_slot) ||
      (m.stage ? knockoutStages.has(m.stage.toUpperCase()) : false)
  );

  return !hasDefinedKnockoutMatches;
}

/**
 * Construye el árbol de llaves eliminatorias (Octavos, Cuartos, Semifinales y Final)
 * sincronizado exclusivamente con los partidos eliminatorios reales de `matches` en Supabase.
 * Si el torneo sigue en Fase de Liga y aún no existen llaves definidas, devuelve los nodos vacíos ("Por definir").
 */
export function buildKnockoutBracketTies(
  standings: StandingRow[],
  matches: MatchWithDetails[]
): KnockoutTieNode[] {
  void standings;

  const emptyTies: KnockoutTieNode[] = [
    ...[1, 2, 3, 4, 5, 6, 7, 8].map(
      (num): KnockoutTieNode => ({
        slot: `R16-${num}`,
        stage: "R16",
        routeLabel: `Octavo ${num} • ${num <= 4 ? "Ruta Plata" : "Ruta Azul"}`,
        dateLabel: "Por definir (Tras Fase de Liga)",
        venueLabel: "Sede por sortear",
        status: "SCHEDULED",
        homeTeam: null,
        awayTeam: null,
        homeLeg1Score: null,
        awayLeg1Score: null,
        homeLeg2Score: null,
        awayLeg2Score: null,
        homeAggregate: null,
        awayAggregate: null,
        winnerTeamId: null,
      })
    ),
    ...[1, 2, 3, 4].map(
      (num): KnockoutTieNode => ({
        slot: `QF-${num}`,
        stage: "QF",
        routeLabel: `Cuartos ${num} • ${num <= 2 ? "Ruta Plata" : "Ruta Azul"}`,
        dateLabel: "Por definir",
        venueLabel: "Sede por definir",
        status: "SCHEDULED",
        homeTeam: null,
        awayTeam: null,
        homeLeg1Score: null,
        awayLeg1Score: null,
        homeLeg2Score: null,
        awayLeg2Score: null,
        homeAggregate: null,
        awayAggregate: null,
        winnerTeamId: null,
      })
    ),
    ...[1, 2].map(
      (num): KnockoutTieNode => ({
        slot: `SF-${num}`,
        stage: "SF",
        routeLabel: `Semifinal ${num} • ${num === 1 ? "Ruta Plata" : "Ruta Azul"}`,
        dateLabel: "Por definir",
        venueLabel: "Sede por definir",
        status: "SCHEDULED",
        homeTeam: null,
        awayTeam: null,
        homeLeg1Score: null,
        awayLeg1Score: null,
        homeLeg2Score: null,
        awayLeg2Score: null,
        homeAggregate: null,
        awayAggregate: null,
        winnerTeamId: null,
      })
    ),
    {
      slot: "FINAL",
      stage: "FINAL",
      routeLabel: "Gran Final • UEFA Champions League",
      dateLabel: "Por definir",
      venueLabel: "Sede Final UEFA",
      status: "SCHEDULED",
      homeTeam: null,
      awayTeam: null,
      homeLeg1Score: null,
      awayLeg1Score: null,
      homeLeg2Score: null,
      awayLeg2Score: null,
      homeAggregate: null,
      awayAggregate: null,
      winnerTeamId: null,
    },
  ];

  const bySlot = new Map<string, MatchWithDetails>();
  for (const m of matches) {
    if (m.bracket_slot) {
      bySlot.set(m.bracket_slot.toUpperCase(), m);
    }
  }

  if (bySlot.size === 0) {
    return emptyTies;
  }

  return emptyTies.map((tie) => {
    const dbMatch = bySlot.get(tie.slot);
    if (!dbMatch) return tie;

    const aggHome = dbMatch.aggregate_home_score ?? dbMatch.home_score;
    const aggAway = dbMatch.aggregate_away_score ?? dbMatch.away_score;

    return {
      ...tie,
      status: dbMatch.status,
      elapsed_minute: dbMatch.elapsed_minute,
      venueLabel: dbMatch.venue ?? tie.venueLabel,
      homeTeam: {
        team_id: dbMatch.home_team_id,
        team_name: dbMatch.home_team_name,
        team_short: dbMatch.home_team_name.slice(0, 3).toUpperCase(),
        team_crest: dbMatch.home_team_crest,
        seed: 1,
      },
      awayTeam: {
        team_id: dbMatch.away_team_id,
        team_name: dbMatch.away_team_name,
        team_short: dbMatch.away_team_name.slice(0, 3).toUpperCase(),
        team_crest: dbMatch.away_team_crest,
        seed: 2,
      },
      homeLeg2Score: dbMatch.home_score,
      awayLeg2Score: dbMatch.away_score,
      homeAggregate: aggHome,
      awayAggregate: aggAway,
      winnerTeamId:
        dbMatch.status === "FINISHED"
          ? aggHome > aggAway
            ? dbMatch.home_team_id
            : aggAway > aggHome
              ? dbMatch.away_team_id
              : null
          : null,
    };
  });
}
